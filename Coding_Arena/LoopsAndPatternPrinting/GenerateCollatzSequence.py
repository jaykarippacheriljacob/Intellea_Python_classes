"""
    Generate Collatz Sequence
    Medium
    General Programming
    The Collatz Conjecture is a famous unsolved problem in mathematics. It proposes a sequence of numbers starting from any positive integer n. The sequence is generated by repeatedly applying the following rules:

    If the current number is even, divide it by 2.
    If the current number is odd, multiply it by 3 and add 1.
    The conjecture states that no matter what value of n you start with, the sequence will always eventually reach 1.

    Your task is to write a function that takes a positive integer n and returns a list containing the Collatz sequence starting from n until it reaches 1.

    Examples

    Arguments: 12
    Returns: [12, 6, 3, 10, 5, 16, 8, 4, 2, 1]
    Explanation: Starting with 12 (even), the sequence is: 12 -> 12/2=6 -> 6/2=3 -> 3*3+1=10 -> 10/2=5 -> 5*3+1=16 -> 16/2=8 -> 8/2=4 -> 4/2=2 -> 2/2=1.
    Arguments: 5
    Returns: [5, 16, 8, 4, 2, 1]
    Explanation: Starting with 5 (odd), the sequence is: 5 -> 5*3+1=16 -> 16/2=8 -> 8/2=4 -> 4/2=2 -> 2/2=1.
    Arguments: 1
    Returns: [1]
    Explanation: The input is 1, which is the stopping condition. The sequence starts and ends with 1.
    Constraints

    The input `n` will be a positive integer, where `1 <= n <= 1,000,000`.
"""

def generate_collatz_sequence(n):
   new = n
   set = []
   set.append(int(new))
   while True:
       if new == 1:
           return set
       if new % 2 == 0:
           new /= 2
           set.append(int(new))
       else:
           new *= 3
           new += 1
           set.append(int(new))