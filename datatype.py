# Data Types in Python

# 1. Numeric Types: int, float, complex
# 2. Sequence Types: list, tuple, range
# 3. Mapping Type: dict
# 4. Set Types: set, frozenset
# 5. Boolean Type: bool
# 6. None Type: NoneType
# 7. Text Type: str

# EXAMPLE:
name = "Jay"
print(f"Type of name: {type(name)}")  # Output: <class 'str'>
print(f"Value of name: {name}")  # Output: Jay

age = 25
print(f"Type of age: {type(age)}")  # Output: <class 'int'>
print(f"Value of age: {age}")  # Output: 25

cgpa = 8.5
print(f"Type of cgpa: {type(cgpa)}")  # Output: <class 'float'>
print(f"Value of cgpa: {cgpa}")  # Output: 8.5

active_student = True
print(f"Type of active_student: {type(active_student)}")  # Output: <class 'bool'>
print(f"Value of active_student: {active_student}")  # Output: True 
